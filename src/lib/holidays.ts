// 한국 공휴일 정적 데이터셋 (피드백 #5)
// 네트워크 없이 클라이언트에서 판정한다. 음력 기반(설날·추석·부처님오신날)과
// 대체공휴일은 매년 날짜가 달라, 아래 목록을 연도별로 직접 관리한다.
//
// ⚠️ 유지보수: 신규 연도는 관보/공공데이터포털 공휴일을 확인해 추가·보정할 것.
//    현재 2024~2027은 음력·대체공휴일 포함, 2028~2030은 양력 고정공휴일만 우선 포함.

// 매년 동일한 양력 고정 공휴일 (월-일)
const FIXED_MMDD = [
  '01-01', // 신정
  '03-01', // 삼일절
  '05-05', // 어린이날
  '06-06', // 현충일
  '08-15', // 광복절
  '10-03', // 개천절
  '10-09', // 한글날
  '12-25', // 크리스마스
]

// 연도별 음력 기반 + 대체공휴일 (양력 'YYYY-MM-DD')
const LUNAR_AND_SUBSTITUTE: Record<string, string[]> = {
  '2024': [
    '2024-02-09', '2024-02-10', '2024-02-11', '2024-02-12', // 설날 연휴 + 대체
    '2024-04-10', // 국회의원 선거(임시공휴일)
    '2024-05-06', // 어린이날 대체
    '2024-05-15', // 부처님오신날
    '2024-09-16', '2024-09-17', '2024-09-18', // 추석 연휴
  ],
  '2025': [
    '2025-01-28', '2025-01-29', '2025-01-30', // 설날 연휴
    '2025-03-03', // 삼일절 대체
    '2025-05-06', // 어린이날/부처님오신날 겹침 → 대체
    '2025-05-05', // 부처님오신날(어린이날과 동일)
    '2025-10-05', '2025-10-06', '2025-10-07', '2025-10-08', // 추석 연휴 + 대체
  ],
  '2026': [
    '2026-02-16', '2026-02-17', '2026-02-18', // 설날 연휴
    '2026-03-02', // 삼일절 대체(3/1 일)
    '2026-05-24', '2026-05-25', // 부처님오신날 + 대체(5/24 일)
    '2026-08-17', // 광복절 대체(8/15 토)
    '2026-09-24', '2026-09-25', '2026-09-26', // 추석 연휴
    '2026-10-05', // 개천절 대체(10/3 토)
  ],
  '2027': [
    '2027-02-06', '2027-02-07', '2027-02-08', '2027-02-09', // 설날 연휴 + 대체
    '2027-05-13', // 부처님오신날
    // 현충일(6/6, 2027년 일요일)은 국경일이 아니라 대체공휴일 대상이 아님 —
    // 예전엔 '2027-06-07'을 대체공휴일로 잘못 넣어뒀던 걸 발견해 제거함
    // (2026-08-06). 대체공휴일 대상: 설날·추석, 어린이날, 국경일 4개
    // (3.1/8.15/10.3/10.9), 부처님오신날, 크리스마스. 신정·현충일은 제외.
    '2027-08-16', // 광복절 대체(8/15 일)
    '2027-09-14', '2027-09-15', '2027-09-16', // 추석 연휴
    '2027-10-04', // 개천절 대체(10/3 일)
    '2027-10-11', // 한글날 대체(10/9 토)
    '2027-12-27', // 크리스마스 대체(12/25 토)
  ],
}

// 판정용 Set 구성 (양력 고정 2024~2030 + 위 목록)
const holidaySet: Set<string> = (() => {
  const set = new Set<string>()
  for (let y = 2024; y <= 2030; y++) {
    for (const mmdd of FIXED_MMDD) set.add(`${y}-${mmdd}`)
  }
  for (const dates of Object.values(LUNAR_AND_SUBSTITUTE)) {
    for (const d of dates) set.add(d)
  }
  return set
})()

/** 'YYYY-MM-DD' 가 공휴일이면 true */
export function isHoliday(dateStr: string): boolean {
  return holidaySet.has(dateStr)
}
